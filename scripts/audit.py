#!/usr/bin/env python3
"""Generate and check a transitive Lean axiom audit for every UV theorem."""
import argparse
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ALLOWED = {"propext", "Classical.choice", "Quot.sound"}


def code_only(text):
    """Remove Lean's nested comments and strings, preserving newlines."""
    result, i, depth = [], 0, 0
    while i < len(text):
        if text.startswith("/-", i):
            depth += 1
            i += 2
        elif depth and text.startswith("-/", i):
            depth -= 1
            i += 2
        elif depth:
            result.append("\n" if text[i] == "\n" else " ")
            i += 1
        elif text.startswith("--", i):
            end = text.find("\n", i)
            i = len(text) if end == -1 else end
        elif text[i] == '"':
            i += 1
            while i < len(text):
                if text[i] == "\\":
                    i += 2
                elif text[i] == '"':
                    i += 1
                    break
                else:
                    i += 1
            result.append(" ")
        else:
            result.append(text[i])
            i += 1
    if depth:
        raise SystemExit("Unclosed Lean comment")
    return "".join(result)


def theorem_names():
    names = []
    for path in sorted((ROOT / "UV").glob("*.lean")):
        source = code_only(path.read_text())
        if re.search(r"\b(sorry|admit|axiom)\b", source):
            raise SystemExit(f"Forbidden proof placeholder or custom axiom in {path.name}")
        namespaces = re.findall(r"^namespace\s+(\S+)", source, re.M)
        if len(namespaces) != 1 or not namespaces[0].startswith("UV"):
            raise SystemExit(f"Expected one explicit UV namespace in {path.name}")
        for match in re.finditer(r"\b(?:theorem|lemma)\s+([\w']+)", source):
            prefix = source[:match.start()].rsplit("\n", 1)[-1]
            if re.search(r"\bprivate\s+$", prefix):
                continue  # Its mangled compiled name is included by the namespace audit.
            names.append(namespaces[0] + "." + match.group(1))
    if not names or len(set(names)) != len(names):
        raise SystemExit("Missing or duplicate theorem names")
    return names


def audit_source(names):
    return (
        "import UV\nimport Lean.Util.CollectAxioms\n\n"
        "-- Generated by scripts/audit.py --write. Audits every local theorem.\n"
        + "\n-- Every source theorem must occur in the compiled environment.\n"
        + "run_cmd do\n"
        + "  let env ← Lean.getEnv\n"
        + "  for name in #[" + ", ".join("`" + name for name in names) + "] do\n"
        + '    unless env.contains name do throwError "Missing theorem {name}"\n'
        + f'  Lean.logInfo "UV theorem inventory passed: {len(names)} theorems"\n'
        + '''
-- Also inspect definitions and generated declarations, independently of the
-- source inventory. Every declaration under UV is checked transitively.
run_cmd do
  let env ← Lean.getEnv
  let allowed : Array Lean.Name := #[`propext, `Classical.choice, `Quot.sound]
  let names := env.constants.toList.filterMap fun (name, _) =>
    if (`UV).isPrefixOf name || name.toString.startsWith "_private.UV." then some name else none
  -- Share the visited set across roots. Every root is traversed, while shared
  -- mathlib proof dependencies are inspected only once.
  let action : Lean.CollectAxioms.M Unit := do
    for name in names do Lean.CollectAxioms.collect name
  let (_, state) := (action.run env).run {}
  for dependency in state.axioms do
    unless allowed.contains dependency do
      throwError "Unapproved axiom {dependency} in UV namespace"
  Lean.logInfo m!"UV namespace audit passed: {names.length} declarations"
  Lean.logInfo m!"UV transitive axioms: {state.axioms.toList}"
'''
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    names = theorem_names()
    expected = audit_source(names)
    path = ROOT / "UVAudit.lean"
    if args.write:
        path.write_text(expected)
        print(f"Generated audit for {len(names)} theorems")
        return
    if not path.exists() or path.read_text() != expected:
        raise SystemExit("Stale UVAudit.lean; run python3 scripts/audit.py --write")
    run = subprocess.run(
        ["lake", "env", "lean", "-DwarningAsError=true", "UVAudit.lean"],
        cwd=ROOT, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
    )
    log = ROOT / ".lake" / "uv-axioms.log"
    log.parent.mkdir(exist_ok=True)
    log.write_text(run.stdout)
    if run.returncode:
        raise SystemExit(run.stdout)
    if f"UV theorem inventory passed: {len(names)} theorems" not in run.stdout:
        raise SystemExit("Incomplete axiom output:\n" + run.stdout)
    if "UV namespace audit passed:" not in run.stdout:
        raise SystemExit("Missing complete namespace audit")
    found = re.findall(r"UV transitive axioms:\s*\[([^]]*)\]", run.stdout)
    if len(found) != 1:
        raise SystemExit("Missing transitive axiom set")
    used = {a.strip() for a in found[0].split(",") if a.strip()}
    if used - ALLOWED:
        raise SystemExit(f"Unapproved axioms: {used - ALLOWED}")
    print(f"PASS: {len(names)} theorems; transitive axioms: {', '.join(sorted(used))}")


if __name__ == "__main__":
    main()
